/**
 * 프론트 연동용 스텁 API. 경로는 {@code /api/v0/**} 이고 {@code api.stub.enabled=true} 일 때만 뜬다.
 *
 * <h2>왜 있나</h2>
 *
 * <p>실제 API({@code /api/v1/**})가 완성되기 전에 프론트가 화면을 붙여 볼 수 있어야 한다.
 * 스텁은 DB 를 건드리지 않고 고정 데이터를 돌려주므로 시드나 상태에 흔들리지 않고 같은 응답을
 * 낸다. 프론트는 base URL 의 버전만 {@code v0} 에서 {@code v1} 으로 바꾸면 그대로 실제 서버로 붙는다.
 *
 * <h2>범위</h2>
 *
 * <p>공연장·공연·구역·좌석·예매·양도 마켓 도메인만 다룬다. 인증은 v1 을 그대로 쓰고, 지갑·티켓·입장·주최사·관리자는
 * 다른 담당자의 도메인이라 여기 없다.
 *
 * <p>양도 마켓은 티켓 도메인이 없어 필요한 최소한의 티켓 상태를
 * {@link com.ssafy.timo.stub.transfer.MarketStubController} 가 직접 들고 있다. 티켓 도메인이 생기면 그쪽
 * 미러 테이블로 옮긴다.
 *
 * <h2>규약을 어떻게 맞추나</h2>
 *
 * <p>각 스텁은 실제 컨트롤러와 <b>같은 {@code *Api} 인터페이스</b>를 구현한다
 * ({@link com.ssafy.timo.domain.concert.controller.ConcertApi} 등). 매핑·검증 애노테이션이
 * 인터페이스에 있어 요청 DTO, 응답 DTO, 검증 규칙, HTTP 메서드가 컴파일 시점에 같아진다.
 * 인터페이스에 메서드를 더하면 스텁도 컴파일이 깨지므로, 스텁이 실제 API 와 어긋난 채 남을 수 없다.
 *
 * <p>검증 실패·비즈니스 예외는 실제와 같은 {@code GlobalExceptionHandler} 가 처리하므로 에러 응답
 * 모양도 같다.
 *
 * <h2>실패 경로를 시험하는 방법</h2>
 *
 * <p>스텁은 상태가 거의 없어 "존재하지 않는 id" 같은 상황을 만들 수 없다. 대신 아래 <b>예약값</b>을
 * 보내면 그 실패를 재현한다. 값은 {@link com.ssafy.timo.stub.StubFixtures} 에 상수로 있다.
 *
 * <ul>
 *   <li>id 가 {@code 404} 인 공연·공연장·구역·좌석·아티스트·주문 → 각 도메인의 NotFound (404)</li>
 *   <li>좌석 {@code 1006} 으로 주문 → 온체인 발행 실패 → 보상 환불 재현 ({@code MINT_FAILED} → {@code REFUNDED})</li>
 * </ul>
 *
 * <h2>상태를 갖는 부분</h2>
 *
 * <p>공연 생성 결과, 좌석 선점·점유, 주문, 매물은 메모리에만 기억한다. 앱을 다시 켜면 초기 상태로 돌아간다.
 * 좌석은 고정 배치도 위에 선점·점유 결과만 덧씌우므로, 선점한 자리를 다시 조회하면
 * {@code RESERVED} 로 보인다. 주문의 온체인 발행과 내 매물의 판매는 흐른 시간으로 흉내 낸다.
 * 여러 스텁이 함께 보는 상태는 {@code *Store} 컴포넌트로 빼 두었다 (좌석·공연).
 *
 * <h2>삭제 시점</h2>
 *
 * <p>프론트가 {@code v1} 으로 옮겨 가면 이 패키지는 통째로 지운다. 실제 코드는 이 패키지에
 * 의존하지 않는다. {@code *Api} 인터페이스는 그때도 남겨 두어도 된다.
 */
