package com.ssafy.timo.domain.seat.entity;

/**
 * 좌석 배치도에 보이는 상태. <b>저장되지 않고 조회할 때마다 유도된다.</b>
 *
 * <p>예전에는 {@code seat.status} 컬럼이었다. 그런데 {@link Seat} 은 공연장에 속한 마스터 데이터라
 * 모든 공연이 같은 행을 공유한다. 판매 상태를 좌석 행에 적으면 9/20 공연에서 팔린 자리가 9/21 공연
 * 좌석표에도 팔린 것으로 보인다. 그래서 컬럼을 없애고 공연별로 유도한다.
 *
 * <p>유도 규칙은 공연 하나를 기준으로 한다.
 *
 * <pre>
 * SOLD      : reservation 에 status='PAID' 행이 있다
 * HELD      : seat_hold 에 status='HELD' 행이 있거나, cancel_offer 에 열린 기회가 있다
 * AVAILABLE : 둘 다 없다
 * </pre>
 *
 * <p>취소된 자리는 따로 표시하지 않는다. 취소되면 찜한 회원 한 명에게 1시간 구매 기회가 가고
 * 그동안은 선점처럼 잠기며, 기회가 끝나면(혹은 뽑을 사람이 없으면) 곧바로 예매 가능이다.
 *
 * <p>같은 좌석이라도 공연이 다르면 상태가 다르다. 그래서 좌석 상태를 묻는 코드는 언제나
 * 공연 id 를 함께 넘겨야 한다.
 */
public enum SeatStatus {

    /** 예매 가능. 이 공연에 대한 유효한 선점도 주문도 없다. */
    AVAILABLE,
    /** 선점됨. 결제 대기 중이라 다른 회원이 잡을 수 없다. */
    HELD,
    /** 판매 완료. 이 공연의 주문이 이 자리를 붙들고 있다. */
    SOLD
}
